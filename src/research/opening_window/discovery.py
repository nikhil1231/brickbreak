# 5. regime: do breakout-like setups only work in some markets?
# --------------------------------------------------------------------------

def regime_split(df: pd.DataFrame, winner_mask: pd.Series,
                 by: str = "mkt_regime") -> pd.DataFrame:
    """Win rate by market state. The direct test of the standing question.

    Reported both on the named regime labels and — by passing a continuous
    column — on `mkt_trend_eff` terciles, because the labels have round
    cut-points and a claim that survives only one labelling is a claim about
    the labelling.
    """
    if by not in df.columns:
        return pd.DataFrame()
    key = df[by]
    if pd.api.types.is_numeric_dtype(key):
        key = pd.qcut(key, 3, labels=["low", "mid", "high"], duplicates="drop")
    rows = []
    for level, sub in df.groupby(key, observed=True):
        if len(sub) < 500:
            continue
        y = winner_mask[sub.index].astype(float) * 100
        s = explore.cluster_stats(y, sub["date"])
        rows.append({by: str(level), "n": len(sub), "n_dates": s["n_dates"],
                     "win_pct": round(float(y.mean()), 2), "t": s["t"]})
    out = pd.DataFrame(rows)
    if len(out) > 1:
        out["vs_pool"] = (out["win_pct"] / (winner_mask.mean() * 100)).round(2)
    return out


def regime_interaction(df: pd.DataFrame, winner_mask: pd.Series,
                       feature: str, by: str = "mkt_regime",
                       q: int = 3, min_n: int = 400) -> pd.DataFrame:
    """Win rate by (regime, feature tercile). Where "only in some regimes" lives.

    A feature that separates winners from failures in a trending market and does
    nothing in chop shows up here and nowhere else — the pooled contrast averages
    the two into something weaker than either.
    """
    if feature not in df.columns or by not in df.columns:
        return pd.DataFrame()
    v = df.groupby("date", sort=False)[feature].rank(pct=True)
    try:
        k = pd.qcut(v, q, labels=[f"q{i+1}" for i in range(q)], duplicates="drop")
    except ValueError:
        return pd.DataFrame()
    rows = []
    for (reg, band), sub in df.groupby([df[by], k], observed=True):
        if len(sub) < min_n:
            continue
        y = winner_mask[sub.index].astype(float) * 100
        s = explore.cluster_stats(y, sub["date"])
        rows.append({"regime": str(reg), "band": str(band), "n": len(sub),
                     "win_pct": round(float(y.mean()), 2), "t": s["t"]})
    return pd.DataFrame(rows)


