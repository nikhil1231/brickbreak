def sensitivity(frame: pd.DataFrame, features: list[str],
                base_cfg: OutcomeConfig | None = None,
                match_cfg: MatchConfig | None = None,
                verbose: bool = True) -> pd.DataFrame:
    """Re-run the top contrasts under nearby definitions of everything.

    The instruction for this phase permits overfitting, which makes this the
    one check that cannot be skipped: a finding that exists at
    `stop_atr_floor=0.5, fast_sessions=3, k=3, caliper=0.20` and nowhere near it
    is a property of those four numbers. Varied here: the risk floor, the
    winner bar, the definition of "fast", the number of controls and the
    caliper. The reported number is the standardised contrast, so the columns
    are comparable down a row.
    """
    base_cfg = base_cfg or OutcomeConfig()
    match_cfg = match_cfg or MatchConfig()
    variants = {
        "base": (base_cfg, match_cfg),
        "risk_floor_0.25": (replace_cfg(base_cfg, stop_atr_floor=0.25), match_cfg),
        "risk_floor_0.75": (replace_cfg(base_cfg, stop_atr_floor=0.75), match_cfg),
        "winner_bar_looser": (replace_cfg(base_cfg, slow_r=1.5, slow_pct=2.0,
                                          clean_r=2.0, clean_pct=4.0), match_cfg),
        "winner_bar_tighter": (replace_cfg(base_cfg, slow_r=3.0, slow_pct=5.0,
                                           clean_r=4.0, clean_pct=8.0), match_cfg),
        "fast_2_sessions": (replace_cfg(base_cfg, fast_sessions=2), match_cfg),
        "k_1_control": (base_cfg, replace_cfg(match_cfg, k=1)),
        "caliper_0.10": (base_cfg, replace_cfg(match_cfg, caliper=0.10,
                                               max_dim_caliper=0.20)),
        "same_session_only": (base_cfg, replace_cfg(match_cfg, date_window=0)),
    }
    out = {}
    for name, (oc, mc) in variants.items():
        p = build_outcomes(frame, oc, verbose=False)
        p = p[p["outcome"].notna()].reset_index(drop=True)
        w = p["outcome"].isin(STRONG)
        c = p["outcome"].isin(FAILURES)
        pairs, st = match(p, w, c, mc, verbose=False)
        if pairs.empty:
            continue
        con = contrasts(p, pairs, features)
        if con.empty:
            continue
        out[name] = con.set_index("feature")["std_diff"]
        if verbose:
            print(f"    {name:20s} {st['matched']:>6,} sets")
    d = pd.DataFrame(out)
    if d.empty:
        return d
    d["sign_stable"] = (np.sign(d).nunique(axis=1) == 1)
    d["min_abs"] = d.drop(columns="sign_stable").abs().min(axis=1)
    return d.round(4)


def replace_cfg(cfg, **kw):
    """`dataclasses.replace` for the frozen configs, kept local for readability."""
    from dataclasses import replace
    return replace(cfg, **kw)


def load_frame(t: int = 180, verbose: bool = True) -> pd.DataFrame:
    """Everything on one row, at one entry time, fenced to the exploration window.

    Four sources: the behavioural opening panel (causal at `t`), the daily
    setup context from the as-of screen, the new breakout-location and
    relative-strength columns, and the per-session market regime. The fence is
    applied first and again after every join, because a join is exactly where a
    holdout row would get in.
    """
    from ...research_data.pipelines import context
    from . import behaviour

    panel = behaviour.load()
    panel = panel[panel["t_offset_s"] == t].copy()
    explore.fence(panel, f"behaviour panel at t={t}")

    cand = repository.candidate_labels()
    ctx_cols = [c for c in (
        "sector", "size_tier", "size_tier_rank", "gap_pct", "deliv_pct",
        "ema_stack_up", "above_ema_mid", "px_vs_ema_mid", "px_vs_ema_fast",
        "ema_mid_slope", "ema_fast_slope", "ret_20d", "ret_60d",
        "dist_52w_high", "bb_width_pctile", "atr_ratio_pctile",
        "base_depth_pctile", "contraction_steps", "nr_k", "vol_squeeze",
        "inside_day", "body_ratio", "n_small_bodies_5", "sec_slope",
        "sector_uptrend_index", "sector_breadth", "open_drift_pct",
    ) if c in cand.columns]
    d = panel.merge(cand[["symbol", "date"] + ctx_cols], on=["symbol", "date"],
                    how="inner")

    ctx, mkt = context.load()
    ctx_keep = ["symbol", "date"] + [c for c in ctx.columns
                                     if c not in ("symbol", "date")]
    d = d.merge(ctx[ctx_keep], on=["symbol", "date"], how="left")
    d = d.merge(mkt[["date"] + [c for c in MARKET_COLS if c in mkt.columns]],
                on="date", how="left")
    explore.fence(d, "discovery frame")

    # The adjusted-basis entry, stop and window extremes the path walk needs.
    a = d["adj_factor"]
    d["entry_px_adj"] = d["price_t"] * a
    d["running_low_t_adj"] = d["running_low_t"] * a
    d["running_high_t_adj"] = d["running_high_t"] * a
    d["stop_px_adj"] = d["running_low_t_adj"] * (1 - 0.10 / 100)
    d["stop_dist_pct"] = (d["stop_px_adj"] / d["entry_px_adj"] - 1) * 100
    bad = (d["stop_px_adj"] >= d["running_low_t_adj"]) | (
        d["running_low_t_adj"] > d["entry_px_adj"] + 1e-9)
    if bad.any():
        raise AssertionError(
            f"{int(bad.sum())} rows violate stop < running_low <= entry at "
            f"t={t}s. The invariant is structural (see H004/AGENTS.md); a "
            f"violation means the low and the price were read at different "
            f"moments and every risk number downstream is meaningless.")

    if verbose:
        print(f"  frame at t={t}s: {len(d):,} mornings, "
              f"{d['symbol'].nunique():,} symbols, {d['date'].nunique():,} sessions, "
              f"{d['date'].min().date()} .. {d['date'].max().date()}")
    return d


def build_outcomes(frame: pd.DataFrame, cfg: OutcomeConfig | None = None,
                   verbose: bool = True) -> pd.DataFrame:
    """Attach the forward path and the outcome archetype."""
    cfg = cfg or OutcomeConfig()
    d = frame.copy()
    # Apply the ATR floor on risk before anything is measured against the stop.
    # The tick-implied stop is kept beside it so the two are comparable and the
    # choice is visible rather than baked in.
    d["stop_px_tick_adj"] = d["stop_px_adj"]
    d["stop_dist_tick_pct"] = d["stop_dist_pct"]
    r_eff = np.maximum(d["stop_dist_pct"].abs(),
                       cfg.stop_atr_floor * d["atr_pct"].fillna(0.0))
    d["stop_px_adj"] = d["entry_px_adj"] * (1 - r_eff / 100)
    d["stop_dist_pct"] = -r_eff
    if (d["stop_px_adj"] > d["running_low_t_adj"] + 1e-9).any():
        raise AssertionError("the ATR floor moved a stop *above* the running "
                             "low, which widening cannot do; check atr_pct")

    bars = repository.daily_bars(
        columns=["symbol", "date", "high", "low", "close"])
    p = forward_paths(d, bars, horizon=cfg.horizon,
                      target_pct=cfg.target_pct, verbose=verbose)
    p["outcome"] = classify(p, cfg)
    return p


