@dataclass(frozen=True)
class MatchConfig:
    """Which dimensions are held fixed, and how tightly.

    Two tiers, on purpose. `core` holds fixed only what makes a comparison fair
    — the session, the sector, the liquidity, the volatility class — and leaves
    every setup dimension free to be discovered. `tight` additionally holds
    fixed the four things a person would say the setups shared (prior run-up,
    base tightness, gap, opening activity), which is the literal reading of
    "superficially similar": if a distinction survives the tight tier, it is not
    a restatement of the checklist.

    `caliper` is in units of within-date percentile rank, averaged over the
    covariates, so 0.20 means "the average covariate matches to within a fifth
    of the cross-section". `k` controls per winner trades variance against
    match quality; 3 is the usual default and `sensitivity()` moves it.
    """
    tier: str = "core"
    k: int = 3
    caliper: float = 0.20
    # A per-covariate caliper as well as the mean one. Without it the mean
    # hides a bad dimension behind two good ones: a 0.40 mismatch on size and
    # two exact matches averages to 0.13 and passes a 0.20 mean caliper, and
    # `balance()` then shows size *over*-corrected to the other side. The mean
    # caliper controls overall closeness; this one stops any single dimension
    # from being traded away.
    max_dim_caliper: float = 0.30
    # Sessions either side of the winner's own from which controls may be
    # drawn. **0, and the reason is a measured confound, not a preference.**
    #
    # The pool has a median of 82 candidates per session across 20 sectors, so
    # a same-session cell is thin and widening the band to +/-2 was the obvious
    # fix: it lifts matched winners from 2,446 to 4,105 and improves balance.
    # It also tripled every headline contrast, and that turned out to be the
    # artefact rather than the improvement. Measured directly: under a +/-2
    # band the winner's own session sits **0.45% lower in the equal-weighted
    # market index** than its controls' sessions, on 71.2% of matched sets.
    # Winners cluster on local market troughs — the win rate is 20.2% in the
    # top third of market volatility against 11.7% in the bottom third — so a
    # control taken two sessions away is systematically further up the market's
    # own swing, and every "the winner opened lower in its base, further below
    # its moving average" contrast partly restates that.
    #
    # The tell was a discontinuity, and it is worth recognising again: the
    # effect goes from |t|=4.3 at a 0-session band to |t|=16.8 at 1 session.
    # A real effect does not triple when one day of slack is added to a
    # matching rule. `market_offset()` reports the diagnostic on every run so
    # this cannot come back quietly.
    date_window: int = 0
    # Categorical dimensions are matched **exactly**, not by rank distance.
    # `size_tier_rank` takes the values 50/100/200/500/750/9999, so its rank is
    # almost all ties and its standardised mean difference is dominated by the
    # 9999 bucket — matching on it looked balanced at 0.03 on liquidity while
    # sitting at -0.18 on size. An exact match on the label has no such failure
    # mode and is what "same size class" actually means.
    exact: tuple[str, ...] = ("sector", "size_tier")
    core: tuple[str, ...] = ("median_tv_20_cr", "atr_pct")
    extra: tuple[str, ...] = ("ret_20d", "bb_width_pctile", "gap_pct",
                              "vol_rel_daily_pct")

    def covariates(self) -> tuple[str, ...]:
        return self.core + (self.extra if self.tier == "tight" else ())


def _rank_within_date(df: pd.DataFrame, cols: list[str]) -> pd.DataFrame:
    """Percentile rank inside each session — the only comparable scale here.

    Matching on raw units would let `median_tv_20_cr` (crores, heavy-tailed
    over four orders of magnitude) dominate the distance and make every other
    covariate decorative.
    """
    g = df.groupby("date", sort=False)
    return pd.DataFrame({c: g[c].rank(pct=True) for c in cols}, index=df.index)


def match(df: pd.DataFrame, winner_mask: pd.Series, control_mask: pd.Series,
          cfg: MatchConfig | None = None, verbose: bool = True
          ) -> tuple[pd.DataFrame, dict]:
    """Nearest-neighbour matching inside a session, without replacement.

    Returns a long frame of (`set_id`, `row`, `role`) plus a diagnostic dict
    reporting how many winners found a full complement of controls and how far
    away those controls were. An unmatched winner is dropped, not stretched: a
    winner with no comparable failure on its own session is a real observation
    about the pool and the count of them is reported rather than papered over.

    Without replacement, and greedy in order of each winner's distance to its
    best available control, so the easiest matches are made first and the
    hard ones are left to compete for what remains — which is the standard way
    to stop one convenient control from being reused across a whole session.
    """
    cfg = cfg or MatchConfig()
    covars = [c for c in cfg.covariates() if c in df.columns]
    if not covars:
        raise ValueError("no matching covariates present in the frame")

    ranks = _rank_within_date(df, covars)
    ok = ranks.notna().all(axis=1)
    w_idx = df.index[winner_mask & ok]
    c_idx = df.index[control_mask & ok]

    sets, stats = [], {"winners": int(len(w_idx)), "matched": 0,
                       "unmatched_no_pool": 0, "unmatched_caliper": 0,
                       "controls_used": 0, "dist": []}
    exact_cols = [c for c in cfg.exact if c in df.columns]
    exact_key = None
    if exact_cols:
        exact_key = df[exact_cols[0]].astype(str)
        for c in exact_cols[1:]:
            exact_key = exact_key + "|" + df[c].astype(str)
    dates = df["date"]

    by_date_c: dict = {d: g for d, g in
                       pd.Series(c_idx, index=dates[c_idx]).groupby(level=0)}
    # Session ordinals, so "within 2 sessions" means two *trading* sessions and
    # not two calendar days across a long weekend.
    sessions = np.sort(dates.unique())
    ordinal = {d: i for i, d in enumerate(sessions)}
    rv = ranks.to_numpy(dtype=float)
    pos = pd.Series(np.arange(len(df)), index=df.index)

    # Used controls are tracked **globally**, not per date. With
    # `date_window > 0` consecutive dates draw on overlapping pools, so a
    # per-date `taken` array lets one convenient control be matched to as many
    # as `2 * date_window + 1` different winners. That silently correlates the
    # matched sets and inflates the effective sample; the test
    # `test_matching_respects_exact_keys_caliper_and_date_band` exists because
    # the first version of this function did exactly that.
    used: set = set()

    for d, w_on_date in pd.Series(w_idx, index=dates[w_idx]).groupby(level=0):
        o = ordinal[np.datetime64(d)]
        near = [sessions[j] for j in
                range(max(0, o - cfg.date_window),
                      min(len(sessions), o + cfg.date_window + 1))]
        chunks = [by_date_c[x] for x in near if x in by_date_c]
        if not chunks:
            stats["unmatched_no_pool"] += len(w_on_date)
            continue
        pool = [x for x in pd.concat(chunks).to_numpy() if x not in used]
        if not pool:
            stats["unmatched_no_pool"] += len(w_on_date)
            continue
        w_list = list(w_on_date.to_numpy())
        pp = pos[pool].to_numpy()
        wp = pos[w_list].to_numpy()
        # Mean absolute rank distance: interpretable in the same units as the
        # caliper, and less dominated by one bad dimension than Euclidean.
        delta = rv[pp][None, :, :] - rv[wp][:, None, :]
        gaps = np.abs(delta)
        dist = gaps.mean(axis=2)
        # Which side of the winner each candidate sits on, averaged over the
        # covariates. Used to balance the controls above and below; see below.
        side = np.sign(delta.mean(axis=2))
        dist = np.where(gaps.max(axis=2) <= cfg.max_dim_caliper, dist, np.inf)
        if exact_key is not None:
            same = (exact_key[w_list].to_numpy()[:, None]
                    == exact_key[pool].to_numpy()[None, :])
            dist = np.where(same, dist, np.inf)
        dist = np.where(dist <= cfg.caliper, dist, np.inf)

        # Greedy, easiest winner first.
        order = np.argsort(np.nanmin(np.where(np.isfinite(dist), dist, np.inf),
                                     axis=1))
        taken = np.zeros(len(pool), dtype=bool)
        for wi in order:
            row = np.where(taken, np.inf, dist[wi])
            # Take controls from **both sides** of the winner rather than the k
            # nearest outright. Greedy nearest-neighbour on a treatment group
            # drawn from one tail of a covariate picks systematically from the
            # near side, and the residual imbalance survives calipers five
            # times tighter than the default — measured, not assumed. Drawing
            # alternately from above and below cancels that to first order and
            # costs nothing when the pool is symmetric.
            ranked_all = np.argsort(row)
            ranked_all = [a for a in ranked_all if np.isfinite(row[a])]
            up = [a for a in ranked_all if side[wi, a] >= 0]
            dn = [a for a in ranked_all if side[wi, a] < 0]
            avail = []
            while len(avail) < cfg.k and (up or dn):
                pick_up = len(avail) % 2 == 0
                src = (up if (pick_up and up) else dn) or up
                avail.append(src.pop(0))
            if not avail:
                stats["unmatched_caliper"] += 1
                continue
            sid = f"{pd.Timestamp(d).date()}#{w_list[wi]}"
            sets.append({"set_id": sid, "idx": w_list[wi], "role": "winner",
                         "dist": 0.0})
            for a in avail:
                taken[a] = True
                used.add(pool[a])
                sets.append({"set_id": sid, "idx": pool[a], "role": "control",
                             "dist": float(row[a])})
                stats["dist"].append(float(row[a]))
            stats["matched"] += 1
            stats["controls_used"] += len(avail)

    out = pd.DataFrame(sets)
    dd = np.array(stats.pop("dist")) if stats["dist"] else np.array([])
    stats["mean_control_dist"] = round(float(dd.mean()), 4) if len(dd) else None
    stats["p90_control_dist"] = (round(float(np.percentile(dd, 90)), 4)
                                 if len(dd) else None)
    stats["controls_per_winner"] = (round(stats["controls_used"]
                                          / max(stats["matched"], 1), 2))
    stats["tier"] = cfg.tier
    stats["covariates"] = covars
    stats["exact_on"] = exact_cols
    stats["date_window"] = cfg.date_window
    if verbose:
        print(f"  match ({cfg.tier}): {stats['matched']:,} of {stats['winners']:,} "
              f"winners matched, {stats['controls_per_winner']} controls each, "
              f"mean rank distance {stats['mean_control_dist']}")
    return out, stats


def balance(df: pd.DataFrame, pairs: pd.DataFrame, cols: list[str]
            ) -> pd.DataFrame:
    """Standardised differences on the matched covariates, before and after.

    Reported in **both** spaces, and the distinction is not pedantry. Matching
    happens on within-date percentile ranks, so the rank-space figure is the
    one that says whether the matcher did its job. The raw-space figure is the
    one a reader interprets — but on a heavy-tailed covariate like
    `median_tv_20_cr` (lognormal, four orders of magnitude) it stays around
    0.12 even under a caliper five times tighter than the default, because a
    0.05 rank gap high in the tail is still a large number of crores. Reading
    only the raw column would send you tightening a caliper that is already
    doing everything it can.
    """
    have = [c for c in cols if c in df.columns]
    w = pairs[pairs["role"] == "winner"]["idx"]
    c = pairs[pairs["role"] == "control"]["idx"]
    ranks = _rank_within_date(df, have)
    rows = []
    for col in have:
        out = {"covariate": col}
        for space, src in (("", df), ("_rank", ranks)):
            x = src.loc[w, col].astype(float)
            y = src.loc[c, col].astype(float)
            allw = src.loc[src.index.isin(w), col].astype(float)
            allo = src[col].astype(float)
            pooled = np.sqrt((x.var() + y.var()) / 2)
            pooled0 = np.sqrt((allw.var() + allo.var()) / 2)
            out[f"smd_before{space}"] = (round(float((allw.mean() - allo.mean())
                                                     / pooled0), 3)
                                         if pooled0 > 0 else np.nan)
            out[f"smd_after{space}"] = (round(float((x.mean() - y.mean()) / pooled), 3)
                                        if pooled > 0 else np.nan)
        rows.append(out)
    return pd.DataFrame(rows)


