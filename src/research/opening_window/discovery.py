def rank_contrasts(c: pd.DataFrame, stab: list[pd.DataFrame],
                   perm: dict, top: int = 20) -> pd.DataFrame:
    """Triage order. Not a score, not a probability, not an argument.

    The composite is deliberately blunt and deliberately punitive: effect size
    in standardised units, clustered t as a fraction of the *permuted* maximum
    (so a feature is measured against what the scan produces from noise, not
    against 1.96), sample size, and sign-stability across periods, sectors and
    regimes. Simplicity enters as a flat bonus for features that need no
    interaction to state.
    """
    if c.empty:
        return c
    d = c.copy()
    for s in stab:
        if not s.empty:
            d = d.merge(s, on="feature", how="left")
    bar = max(perm.get("perm_max_t_p95") or 0.0, 1e-9)
    d["t_vs_perm"] = (d["t"].abs() / bar).round(3)
    sign_cols = [x for x in d.columns if x.endswith("_sign_frac")]
    d["sign_frac_mean"] = d[sign_cols].mean(axis=1) if sign_cols else 0.0
    d["triage"] = (
        (d["std_diff"].abs().clip(0, 0.5) / 0.5) * 0.30
        + d["t_vs_perm"].clip(0, 1.5) / 1.5 * 0.30
        + (np.log10(d["n"].clip(lower=1)) / 4.0).clip(0, 1) * 0.10
        + d["sign_frac_mean"].fillna(0.0) * 0.30
    ).round(4)
    return d.sort_values("triage", ascending=False).head(top).reset_index(drop=True)


def build_frozen(rep: dict, sign_frac_min: float = 0.70) -> dict:
    """Pick the survivors and write down exactly what would be tested later.

    Four gates, all of which a candidate must pass:

    1. **Beats the search-corrected bar**: |t| above the 95th percentile of the
       permuted maximum, not above 1.96. A scan over 68 features produces a
       best |t| near 3.4 from noise alone on this design.
    2. **Survives the tight tier**: still present when prior run-up, base
       width, gap and opening volume are held fixed. A distinction that only
       exists in the core tier is a restatement of the screening checklist.
    3. **Keeps its sign** across subperiods, sectors and market regimes.
    4. **Keeps its sign** across every nearby definition in `sensitivity()`.

    What is written is the *definition*, never the number: the entry time, the
    outcome config, the match config, the feature and the direction. A frozen
    finding that has to be re-derived before it can be tested is not frozen,
    and the whole value of the 2020-2023 backfill rests on the holdout run
    testing this rule rather than a cousin of it.
    """
    core = rep.get("tiers", {}).get("core", {})
    tight = rep.get("tiers", {}).get("tight", {})
    if not core:
        return {"candidates": [], "note": "no core tier in the report"}
    bar = core["permutation_null"]["perm_max_t_p95"]
    tight_t = {r["feature"]: r["t"] for r in tight.get("contrasts", [])}
    tight_n = tight.get("match", {}).get("matched", 0)
    ranked = {r["feature"]: r for r in core.get("ranked", [])}
    sens = {r["feature"]: r for r in rep.get("sensitivity", [])}

    cands, near = [], []
    for r in core["contrasts"]:
        f = r["feature"]
        if abs(r["t"]) <= bar:
            continue
        tt = tight_t.get(f)
        rk = ranked.get(f, {})
        sf = [rk.get(k) for k in ("period_sign_frac", "sector_sign_frac",
                                  "mkt_regime_sign_frac")]
        sf = [x for x in sf if x is not None and not pd.isna(x)]
        if sf and float(np.mean(sf)) < sign_frac_min:
            continue
        sv = sens.get(f, {})
        if sv and sv.get("sign_stable") is False:
            continue
        rec = {
            "id": f"DISC-{f}",
            "feature": f,
            "family": family_of(f),
            "direction": "winners_lower" if r["t"] < 0 else "winners_higher",
            "core_t": r["t"], "tight_t": tt,
            "std_diff": r["std_diff"],
            "n_sets_core": r["n"],
            "n_sets_tight": tight_n,
            "sign_frac_mean": round(float(np.mean(sf)), 3) if sf else None,
            "sensitivity_min_abs_std_diff": sv.get("min_abs"),
        }
        # The tight tier is the fourth gate and it is also the weakest test in
        # the set: holding prior run-up, base width, gap and opening volume
        # fixed as well leaves only a few hundred matched sets, and the
        # permutation bar barely moves. Failing it is therefore weak evidence
        # of absence, and a feature that clears everything else is recorded as
        # a near miss rather than discarded — with the sample size beside it,
        # so the reader can see it is a power problem and not a contradiction.
        if tt is not None and np.sign(tt) == np.sign(r["t"]) and abs(tt) > bar:
            cands.append(rec)
        else:
            rec["failed_gate"] = "tight_tier"
            rec["note"] = (f"tight tier has {tight_n} sets against "
                           f"{r['n']} in core; underpowered, not contradictory"
                           if tight_n else "absent from the tight tier")
            near.append(rec)

    # The structures that are not single features. Regime splits are frozen on
    # their own terms: they are measured on the whole pool rather than on
    # matched sets, so the matching gates do not apply to them and the thing to
    # replay is the split itself.
    for key, direction in (("mkt_regime", "win_rate_higher_in_chop"),
                           ("mkt_vol_20d", "win_rate_higher_in_high_market_vol"),
                           ("mkt_trend_eff", "win_rate_higher_when_market_is_not_trending")):
        detail = rep.get("regime", {}).get(key, [])
        if not detail:
            continue
        spread = max(x["win_pct"] for x in detail) / max(
            min(x["win_pct"] for x in detail), 1e-9)
        cands.append({
            "id": f"DISC-regime-{key}",
            "feature": key,
            "family": "market_regime",
            "direction": direction,
            "max_min_win_ratio": round(float(spread), 2),
            "detail": detail,
        })
    nl = rep.get("clusters", {}).get("neighbourhood_lift", {}).get("5.0", [])
    if nl:
        best = max(nl, key=lambda x: x.get("lift") or 0)
        cands.append({
            "id": "DISC-winner-neighbourhood",
            "feature": "cluster_centroid",
            "family": "multivariate",
            "direction": "win_rate_higher_near_centroid",
            "cluster": best["cluster"], "lift": best["lift"],
            "radius_pctile": 5.0,
            "centroid": rep["clusters"]["centroids"][int(best["cluster"])],
            "centroid_features": rep["clusters"]["features"],
        })

    return {
        "generated": "reverse discovery, exploration window only",
        "status": "EXPLORATORY / DATA-GENERATED — not confirmed by this data",
        "exploration_window": rep.get("window"),
        "holdout_window": ["2020-04-27", str(explore.EXPLORE_START.date())],
        "replay": {
            "t_offset_s": rep["t_offset_s"],
            "outcome_config": asdict(OutcomeConfig()),
            "match_config": asdict(MatchConfig()),
            "cluster_config": asdict(ClusterConfig()),
            "winner_states": list(STRONG),
            "failure_states": list(FAILURES),
            "base_win_rate_pct": rep.get("base_win_rate_pct"),
            "permutation_bar_t": bar,
        },
        "candidates": cands,
        "near_miss": near,
    }


def freeze(payload: dict, path=FROZEN_PATH) -> None:
    """Write the survivors in a form the holdout run can replay unchanged.

    The definitions, not the numbers: the outcome config, the matching config,
    the cluster centroids and their feature order, the radius, and the exact
    `t`. A frozen finding that has to be re-derived before it can be tested is
    not frozen, and the whole value of the 2020-2023 backfill rests on the test
    being of *this* rule rather than of a cousin of it.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, default=str))
    print(f"\n-> froze {len(payload.get('candidates', []))} candidate structures "
          f"to {path.relative_to(config.PROJECT_ROOT)}")


