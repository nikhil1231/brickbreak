@dataclass(frozen=True)
class OutcomeConfig:
    """The taxonomy's definition. Every bar is `max(R-multiple, absolute)`.

    `target_pct` is the uncle's stated +15%. `fast_sessions` is where "the move
    happened quickly" is drawn and is the one number here with no external
    source; `sensitivity()` moves it.

    `stop_atr_floor` is the correction that matters most, and it is a
    measurement, not a preference. The stop implied by "slightly below the
    running low" at t=180s has a **median distance of 0.41%** on this pool
    against a **median ATR of 3.37%** — one eighth of a normal day's range. A
    stop that tight is not a risk level, it is the bid-ask spread with a name,
    and every outcome defined against it would really be measuring "did this
    stock wiggle in the next twenty minutes". Risk is therefore floored at
    `stop_atr_floor x atr_pct`, which lifts the median R to 1.70% and lands in
    the same neighbourhood as the 2.41% the Phase 2.4b entry-window work
    measured for setups that had actually advanced. Widening a stop can never
    break `stop < running_low <= entry`, so the invariant survives untouched;
    narrowing one would, and nothing here narrows.
    """
    horizon: int = 10
    stop_atr_floor: float = 0.5
    target_pct: float = 15.0
    monster_r: float = 6.0
    clean_r: float = 3.0
    clean_pct: float = 6.0
    slow_r: float = 2.0
    slow_pct: float = 3.0
    prior_gain_r: float = 1.0
    prior_gain_pct: float = 2.0
    fast_sessions: int = 3
    immediate_sessions: int = 1


def forward_paths(trades: pd.DataFrame, bars: pd.DataFrame,
                  horizon: int = 10, target_pct: float = 15.0,
                  verbose: bool = True) -> pd.DataFrame:
    """Per-session forward path for each trade, resolved against the open window.

    The entry day needs care and gets the same treatment as `payoff.simulate`:
    an extreme that was already set *inside* the opening window is not reachable
    after the entry, so the entry day's post-entry high is the daily high only
    when that high exceeds the window's own running high, and likewise for the
    low. Skipping that step credits the trade with the part of the day it
    already watched go by.

    Returns cumulative MFE/MAE by session together with the three timing facts
    the taxonomy needs: when the stop was first touched, when the favourable
    excursion peaked, and how much favourable excursion happened *before* any
    stop.
    """
    b = bars.sort_values(["symbol", "date"]).reset_index(drop=True)
    arrays, index = {}, {}
    for sym, g in b.groupby("symbol", sort=False):
        arrays[sym] = (g["high"].to_numpy(dtype=float),
                       g["low"].to_numpy(dtype=float),
                       g["close"].to_numpy(dtype=float))
        index[sym] = pd.Series(np.arange(len(g)), index=g["date"].to_numpy())

    n, H = len(trades), horizon
    hi = np.full((n, H + 1), np.nan)
    lo = np.full((n, H + 1), np.nan)
    cl = np.full((n, H + 1), np.nan)
    n_sess = np.zeros(n, dtype=int)

    syms = trades["symbol"].to_numpy()
    dates = trades["date"].to_numpy()
    for k in range(n):
        a = arrays.get(syms[k])
        if a is None:
            continue
        pos = index[syms[k]].get(dates[k], None)
        if pos is None:
            continue
        i0 = int(pos)
        h, l, c = a
        end = min(i0 + H, len(c) - 1)
        n_sess[k] = end - i0
        m = end - i0 + 1
        hi[k, :m] = h[i0:end + 1]
        lo[k, :m] = l[i0:end + 1]
        cl[k, :m] = c[i0:end + 1]

    # Entry-day resolution: unreachable extremes become -inf / +inf so they
    # cannot win a cumulative max / min.
    rl = trades["running_low_t_adj"].to_numpy(dtype=float)
    rh = trades["running_high_t_adj"].to_numpy(dtype=float)
    hi[:, 0] = np.where(hi[:, 0] > rh + 1e-9, hi[:, 0], -np.inf)
    lo[:, 0] = np.where(lo[:, 0] < rl - 1e-9, lo[:, 0], np.inf)

    entry = trades["entry_px_adj"].to_numpy(dtype=float)
    stop = trades["stop_px_adj"].to_numpy(dtype=float)
    e = entry[:, None]

    run_hi = np.fmax.accumulate(np.where(np.isnan(hi), -np.inf, hi), axis=1)
    run_lo = np.fmin.accumulate(np.where(np.isnan(lo), np.inf, lo), axis=1)
    mfe = (run_hi / e - 1) * 100
    mae = (run_lo / e - 1) * 100
    mfe[~np.isfinite(mfe)] = np.nan
    mae[~np.isfinite(mae)] = np.nan

    out = trades.copy()
    out["n_fwd_sessions"] = n_sess
    complete = n_sess >= H
    out["path_complete"] = complete

    # Session index (0 = entry day) of the first stop touch and of the first
    # touch of the stated target. `argmax` over a boolean gives the first True;
    # a row with no True is masked back to -1 explicitly rather than silently
    # reading as session 0.
    stop_hit = np.where(np.isnan(lo), False, lo <= stop[:, None])
    tgt_hit = np.where(np.isnan(hi), False,
                       hi >= (entry * (1 + target_pct / 100))[:, None])
    out["sess_to_stop"] = np.where(stop_hit.any(axis=1), stop_hit.argmax(axis=1), -1)
    out["sess_to_target"] = np.where(tgt_hit.any(axis=1), tgt_hit.argmax(axis=1), -1)

    # Peak favourable excursion and when it happened.
    # An all-NaN row (symbol absent from the bars) reduces to NaN rather than
    # raising a warning and returning -inf, which would sort as the worst
    # possible outcome instead of as "unknown".
    any_bar = np.isfinite(mfe).any(axis=1)
    out["mfe_pct"] = np.where(any_bar, np.nanmax(np.where(np.isfinite(mfe), mfe,
                                                          -np.inf), axis=1), np.nan)
    out["mae_pct"] = np.where(any_bar, np.nanmin(np.where(np.isfinite(mae), mae,
                                                          np.inf), axis=1), np.nan)
    per_sess = (np.where(np.isnan(hi), -np.inf, hi) / e - 1) * 100
    out["sess_to_mfe"] = np.where(np.isfinite(per_sess), per_sess,
                                  -np.inf).argmax(axis=1)

    # How much the trade had made *before* the stop was first touched. This is
    # the distinction between "it worked then broke" and "it never worked", and
    # it is the whole reason the taxonomy is path-aware.
    idx = np.arange(H + 1)[None, :]
    s = out["sess_to_stop"].to_numpy()
    before = np.where(s[:, None] < 0, True, idx < s[:, None])
    pre = np.where(before, mfe, np.nan)
    with np.errstate(invalid="ignore"):
        out["mfe_before_stop_pct"] = np.nanmax(
            np.where(np.isnan(pre), -np.inf, pre), axis=1)
    out.loc[~np.isfinite(out["mfe_before_stop_pct"]), "mfe_before_stop_pct"] = np.nan

    ret = (cl / e - 1) * 100
    out["ret_h_pct"] = np.where(complete, ret[:, H], np.nan)
    out["ret_5d_pct"] = np.where(n_sess >= 5, ret[:, min(5, H)], np.nan)
    fwd_cl = np.where(idx[:, 1:] <= n_sess[:, None], ret[:, 1:], np.nan)
    with np.errstate(invalid="ignore"):
        out["frac_closes_above_entry"] = np.nanmean(fwd_cl > 0, axis=1)

    if verbose:
        print(f"  forward paths: {int(complete.sum()):,} of {n:,} trades have a "
              f"complete {H}-session path")
    return out


def classify(paths: pd.DataFrame, cfg: OutcomeConfig | None = None) -> pd.Series:
    """One outcome archetype per trade, by a precedence ladder.

    The ladder runs from most to least specific, exactly as `archetypes.py`
    does for the opening window, and the order carries meaning: a morning that
    reached the target and later stopped out is a `monster` (it gave you the
    trade), while one that stopped out first and then ran is not (you were not
    in it). That ordering is a modelling choice about a strategy that exits on
    the stop, not a fact about the tape.
    """
    cfg = cfg or OutcomeConfig()
    R = paths["stop_dist_pct"].abs()
    mfe, mae = paths["mfe_pct"], paths["mae_pct"]
    pre = paths["mfe_before_stop_pct"]
    s_stop, s_tgt, s_mfe = (paths["sess_to_stop"], paths["sess_to_target"],
                            paths["sess_to_mfe"])
    stopped = s_stop >= 0
    # "The stop did not take you out before the favourable move happened."
    survived = ~stopped | (s_stop > s_mfe)

    clean_bar = np.maximum(cfg.clean_r * R, cfg.clean_pct)
    slow_bar = np.maximum(cfg.slow_r * R, cfg.slow_pct)
    prior_bar = np.maximum(cfg.prior_gain_r * R, cfg.prior_gain_pct)

    # "The move was still there at the horizon." Without this test a state can
    # have a large MFE, a fast one, and no profit — which is exactly what the
    # first version of `clean_winner` turned out to be.
    held = paths["ret_h_pct"] > 0

    cond = {
        # Reached the stated +15% target, and was not stopped out first.
        "monster": (s_tgt >= 0) & (~stopped | (s_stop > s_tgt)),
        "clean_winner": (mfe >= clean_bar) & survived & held
                        & (s_mfe <= cfg.fast_sessions),
        "slow_winner": (mfe >= slow_bar) & survived & held
                       & (s_mfe > cfg.fast_sessions),
        # It worked first, then broke. The classic failure, and the one whose
        # setup is hardest to tell from a winner's at the decision point.
        "failed_breakout": stopped & (pre >= prior_bar),
        # Stopped out early, and *then* the stock made the move. The setup may
        # have been right and the stop wrong; separating this from the states
        # where nothing happened is the point of a path-aware taxonomy, because
        # the two have opposite implications for what to change.
        "shaken_out": stopped & (pre.fillna(-99) < prior_bar) & (mfe >= slow_bar),
        # It went somewhere real without being stopped on the way, and gave the
        # whole thing back. Not the same object as a failed breakout: nothing
        # took you out, the move simply evaporated.
        "spike_and_fade": survived & (mfe >= slow_bar) & ~held,
        "immediate_failure": stopped & (s_stop <= cfg.immediate_sessions)
                             & (pre.fillna(-99) < prior_bar),
        "stopped_out": stopped,
        "nothingburger": pd.Series(True, index=paths.index),
    }
    out = pd.Series(pd.NA, index=paths.index, dtype=object)
    assigned = pd.Series(False, index=paths.index)
    for name in OUTCOMES:
        m = cond[name].fillna(False) & ~assigned
        out[m] = name
        assigned |= m
    # A trade whose path is incomplete has no outcome. Left NA rather than
    # bucketed, so a truncated tail cannot masquerade as a nothingburger.
    out[~paths["path_complete"]] = pd.NA
    return pd.Categorical(out, categories=list(OUTCOMES))


def outcome_profile(paths: pd.DataFrame, col: str = "outcome") -> pd.DataFrame:
    """What each outcome state actually looks like. Descriptive."""
    rows = []
    for name, sub in paths.groupby(col, observed=True):
        if not len(sub):
            continue
        rows.append({
            "outcome": str(name),
            "n": len(sub),
            "share_pct": round(len(sub) / paths[col].notna().sum() * 100, 2),
            "med_mfe": round(float(sub["mfe_pct"].median()), 2),
            "med_mae": round(float(sub["mae_pct"].median()), 2),
            "med_ret_h": round(float(sub["ret_h_pct"].median()), 2),
            "mean_ret_h": round(float(sub["ret_h_pct"].mean()), 2),
            "med_R": round(float(sub["stop_dist_pct"].abs().median()), 2),
            "med_sess_to_mfe": float(sub["sess_to_mfe"].median()),
            "pct_stopped": round(float((sub["sess_to_stop"] >= 0).mean() * 100), 1),
        })
    return pd.DataFrame(rows).sort_values("med_ret_h", ascending=False)


def validate_against_payoff(paths: pd.DataFrame, verbose: bool = True
                            ) -> pd.DataFrame:
    """Run the stated exit rule over each outcome state and report what it earned.

    This is the check that keeps the taxonomy from being a naming exercise. A
    state called `clean_winner` has to be worth something under the rule the
    strategy actually uses — enter, stop the losers, scale half at +15%, trail
    the rest — and if it is not, the label is wrong and gets changed. That is
    what happened: the first taxonomy's `clean_winner` (large MFE, reached
    fast) simulated at **-0.12% raw / +0.05% excess** with only 10% of trades
    filling the target, so it was split off as `spike_and_fade` and the winner
    set was narrowed to the three states that do pay.

    Cheap, and it closes the loop between the label and the money.
    """
    from . import payoff
    bars = repository.daily_bars(
        columns=["symbol", "date", "open", "high", "low", "close"])
    t = paths.loc[paths["outcome"].notna(),
                  ["symbol", "date", "entry_px_adj", "stop_px_adj",
                   "running_low_t_adj", "running_high_t_adj", "outcome"]
                  ].rename(columns={"running_low_t_adj": "running_low_t",
                                    "running_high_t_adj": "running_high_t"})
    sim = payoff.attach_benchmark(payoff.simulate(t, bars, verbose=False), bars)
    out = sim.groupby("outcome", observed=True).agg(
        n=("payoff_ret_pct", "size"),
        payoff_pct=("payoff_ret_pct", "mean"),
        excess_pct=("payoff_excess_pct", "mean"),
        median_pct=("payoff_ret_pct", "median"),
        sessions_held=("sessions_held", "median"),
        target_fill_pct=("target_filled", "mean"),
    ).round(3).reset_index()
    out["target_fill_pct"] = (out["target_fill_pct"] * 100).round(1)
    out["is_winner"] = out["outcome"].isin(STRONG)
    if verbose:
        print(out.to_string(index=False))
    return out


