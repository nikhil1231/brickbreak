def market_offset(df: pd.DataFrame, pairs: pd.DataFrame) -> dict:
    """How far the winners' own sessions sat from their controls', in market terms.

    The standing guard against the confound documented on `MatchConfig`. With
    same-session matching this is exactly zero by construction, and reporting a
    zero every run is the point: the moment somebody widens `date_window` for
    a perfectly good reason, the number stops being zero and the inflated
    contrasts that follow are labelled rather than believed.
    """
    from ...research_data.pipelines import context
    try:
        _, mkt = context.load()
    except RuntimeError:
        return {}
    mi = mkt.set_index("date")["mkt_index"]
    w = pairs[pairs["role"] == "winner"].set_index("set_id")["idx"]
    c = pairs[pairs["role"] == "control"]
    wm = pd.Series(mi.reindex(df.loc[w.to_numpy(), "date"].to_numpy()).to_numpy(),
                   index=w.index)
    cm = pd.Series(mi.reindex(df.loc[c["idx"].to_numpy(), "date"].to_numpy()
                              ).to_numpy(),
                   index=c["set_id"].to_numpy()).groupby(level=0).mean()
    rel = (wm / cm.reindex(wm.index) - 1) * 100
    return {"mean_pct": round(float(rel.mean()), 4),
            "median_pct": round(float(rel.median()), 4),
            "pct_sets_winner_below": round(float((rel < 0).mean() * 100), 1)}


def contrasts(df: pd.DataFrame, pairs: pd.DataFrame, features: list[str],
              min_sets: int = 200) -> pd.DataFrame:
    """For every feature: winner minus the mean of its own matched controls.

    Reported in two units. `mean_diff` is the raw difference and is what a
    person reads. `std_diff` divides by the pooled within-date standard
    deviation of the feature, which is the only unit in which
    `days_since_high_50` and `uptick_vol_share` can be ranked against each
    other.

    Inference is clustered on the session. Matched sets on the same date are not
    independent — that is the entire reason same-date matching works — so
    treating each set as an observation would inflate every t here by roughly
    the same factor H016 measured for the row-level scans.
    """
    have = [f for f in features if f in df.columns]
    w = pairs[pairs["role"] == "winner"].set_index("set_id")["idx"]
    c = pairs[pairs["role"] == "control"]
    set_dates = df.loc[w.to_numpy(), "date"].to_numpy()

    num = df[have].apply(pd.to_numeric, errors="coerce")
    ctrl_mean = num.loc[c["idx"].to_numpy()].groupby(
        c["set_id"].to_numpy()).mean()
    win_vals = num.loc[w.to_numpy()]
    win_vals.index = w.index
    diff = win_vals - ctrl_mean.reindex(win_vals.index)
    diff["date"] = set_dates

    # Pooled within-date SD, so the standardised unit is not inflated by
    # between-session drift in the feature itself.
    within_sd = num.groupby(df["date"].to_numpy()).transform("std").mean()

    rows = []
    for f in have:
        y = diff[f]
        if y.notna().sum() < min_sets:
            continue
        s = explore.cluster_stats(y, diff["date"])
        sd = float(within_sd.get(f, np.nan))
        md = s.pop("mean")
        s["feature"] = f
        s["family"] = family_of(f)
        s["mean_diff"] = md
        s["std_diff"] = round(md / sd, 4) if sd and sd > 0 else np.nan
        s["pct_winner_higher"] = s.pop("hit_pct")
        rows.append(s)
    out = pd.DataFrame(rows)
    if out.empty:
        return out
    return out.reindex(out["t"].abs().sort_values(ascending=False).index
                       ).reset_index(drop=True)


def permutation_null(df: pd.DataFrame, pairs: pd.DataFrame,
                     features: list[str], n_perm: int = 200, seed: int = 0
                     ) -> dict:
    """The bar a scan has to clear: max |t| when the winner label is shuffled.

    Inside each matched set, which member is called the winner is permuted. The
    session, the sector, the liquidity, the whole joint distribution of the
    stratum survives untouched; only the association between winning and the
    feature values is destroyed. That makes this the *right* null for this
    design, in the same way the within-date shuffle was the right one for
    `explore.permutation_max` — and for the same reason the earlier
    between-date shuffle there was vacuous.

    Vectorised over sets rather than looped, because the honest version of this
    test is 200 permutations x 60 features x 5,000 sets and the looped form
    takes long enough that it would quietly get run at n_perm=20.
    """
    rng = np.random.default_rng(seed)
    have = [f for f in features if f in df.columns]
    num = df[have].apply(pd.to_numeric, errors="coerce")

    sid = pairs["set_id"].to_numpy()
    idx = pairs["idx"].to_numpy()
    codes, uniq = pd.factorize(sid)
    n_sets, F = len(uniq), len(have)

    order = np.argsort(codes, kind="stable")
    codes_s, idx_s = codes[order], idx[order]
    starts = np.searchsorted(codes_s, np.arange(n_sets))
    sizes = np.append(starts[1:], len(codes_s)) - starts
    width = int(sizes.max())

    # Padded (n_sets, width) matrix of member row positions, and a mask.
    pos = pd.Series(np.arange(len(df)), index=df.index)
    member = np.zeros((n_sets, width), dtype=int)
    mask = np.zeros((n_sets, width), dtype=bool)
    ar = np.arange(width)
    member[ar[None, :] < sizes[:, None]] = pos[idx_s].to_numpy()
    mask = ar[None, :] < sizes[:, None]

    vals = num.to_numpy(dtype=float)
    v = np.where(mask[:, :, None], vals[member], np.nan)      # (sets, width, F)
    tot = np.nansum(np.where(np.isnan(v), 0.0, v), axis=1)
    cnt = np.sum(mask[:, :, None] & ~np.isnan(v), axis=1)

    set_dates = pd.Series(df["date"].to_numpy()[member[:, 0]])
    d_codes, _ = pd.factorize(set_dates)
    n_d = d_codes.max() + 1

    def _max_abs_t(diff: np.ndarray) -> float:
        """Clustered t for every feature at once; returns the largest |t|."""
        ok = np.isfinite(diff)
        n = ok.sum(axis=0)
        mean = np.where(n > 0, np.nansum(np.where(ok, diff, 0.0), axis=0)
                        / np.maximum(n, 1), np.nan)
        resid = np.where(ok, diff - mean, 0.0)
        by_date = np.zeros((n_d, F))
        np.add.at(by_date, d_codes, resid)
        g = n_d
        var = (by_date ** 2).sum(axis=0) / np.maximum(n, 1) ** 2
        if g > 1:
            var *= g / (g - 1)
        se = np.sqrt(var)
        with np.errstate(invalid="ignore", divide="ignore"):
            t = np.where(se > 0, mean / se, 0.0)
        return float(np.nanmax(np.abs(t))) if F else 0.0

    maxes = []
    for _ in range(n_perm):
        pick = (rng.random(n_sets) * sizes).astype(int)
        wsel = np.take_along_axis(member, pick[:, None], axis=1)[:, 0]
        wv = vals[wsel]
        # Control mean = (total over the set - the chosen winner) / (n - 1).
        cn = cnt - np.isfinite(wv)
        cm = np.where(cn > 0, (tot - np.where(np.isfinite(wv), wv, 0.0))
                      / np.maximum(cn, 1), np.nan)
        maxes.append(_max_abs_t(wv - cm))

    m = np.array(maxes)
    return {"n_perm": int(n_perm), "n_features": F, "n_sets": int(n_sets),
            "perm_max_t_p50": round(float(np.percentile(m, 50)), 2),
            "perm_max_t_p90": round(float(np.percentile(m, 90)), 2),
            "perm_max_t_p95": round(float(np.percentile(m, 95)), 2),
            "perm_max_t_max": round(float(m.max()), 2)}


def win_rate_profile(df: pd.DataFrame, winner_mask: pd.Series, feature: str,
                     q: int = 5, min_n: int = 400) -> pd.DataFrame:
    """Win rate by quintile of one feature, ranked within the session.

    The reader-facing form of a contrast. `contrasts()` says winners had a
    lower X than their matched failures; this says what fraction of mornings in
    each band of X went on to win, which is the number a person can act on and
    the one that exposes a non-monotone relationship a mean difference would
    hide entirely.
    """
    if feature not in df.columns:
        return pd.DataFrame()
    v = df.groupby("date", sort=False)[feature].rank(pct=True)
    try:
        k = pd.qcut(v, q, labels=False, duplicates="drop")
    except ValueError:
        return pd.DataFrame()
    base = float(winner_mask.mean() * 100)
    rows = []
    for band, sub in df.groupby(k, observed=True):
        if len(sub) < min_n:
            continue
        y = winner_mask[sub.index].astype(float) * 100
        st = explore.cluster_stats(y, sub["date"])
        rows.append({
            "feature": feature, "band": int(band) + 1, "n": len(sub),
            "lo": round(float(sub[feature].min()), 3),
            "hi": round(float(sub[feature].max()), 3),
            "win_pct": round(float(y.mean()), 2),
            "lift": round(float(y.mean()) / base, 2) if base > 0 else np.nan,
            "t": st["t"],
        })
    return pd.DataFrame(rows)


def stratified_win_rate(df: pd.DataFrame, winner_mask: pd.Series,
                        feature: str, control: str, q: int = 4,
                        min_n: int = 300) -> pd.DataFrame:
    """Win rate by (control band, feature band). The confounding test.

    Written for one specific worry and general enough for the rest of them: the
    strongest single contrast in this phase is that winners opened *lower* in
    their base and further below their moving averages, and the obvious
    mechanical reading is "a stock further below its average simply has more
    room to travel, so it clears an MFE bar more easily". If that were all it
    was, the effect would vanish inside a narrow band of the extension variable.
    This holds the control fixed in quartiles and re-reads the feature inside
    each, which answers the question directly rather than by argument.
    """
    for c in (feature, control):
        if c not in df.columns:
            return pd.DataFrame()
    g = df.groupby("date", sort=False)
    fk = pd.qcut(g[feature].rank(pct=True), q, labels=False, duplicates="drop")
    ck = pd.qcut(g[control].rank(pct=True), q, labels=False, duplicates="drop")
    base = float(winner_mask.mean() * 100)
    rows = []
    for (ci, fi), sub in df.groupby([ck, fk], observed=True):
        if len(sub) < min_n:
            continue
        y = winner_mask[sub.index].astype(float) * 100
        st = explore.cluster_stats(y, sub["date"])
        rows.append({"control_band": int(ci) + 1, "feature_band": int(fi) + 1,
                     "n": len(sub), "win_pct": round(float(y.mean()), 2),
                     "lift": round(float(y.mean()) / base, 2), "t": st["t"]})
    out = pd.DataFrame(rows)
    if out.empty:
        return out
    return out.pivot(index="control_band", columns="feature_band",
                     values="win_pct")


def contrast_stability(df: pd.DataFrame, pairs: pd.DataFrame,
                       features: list[str], by: str, min_sets: int = 60
                       ) -> pd.DataFrame:
    """The same contrasts, cut by subperiod / sector / market regime.

    Reports the fraction of subsets keeping the full-sample sign. A distinction
    that exists in one year or one sector is a distinction about that year or
    that sector.
    """
    w = pairs[pairs["role"] == "winner"].set_index("set_id")["idx"]
    if by == "period":
        key = pd.cut(df.loc[w.to_numpy(), "date"].rank(pct=True),
                     [0, 1 / 3, 2 / 3, 1.0], labels=["p1", "p2", "p3"],
                     include_lowest=True)
    elif by in df.columns:
        key = df.loc[w.to_numpy(), by]
    else:
        return pd.DataFrame()
    key = pd.Series(np.asarray(key), index=w.index)

    full = contrasts(df, pairs, features, min_sets=min_sets)
    if full.empty:
        return full
    sub_means: dict[str, list[float]] = {f: [] for f in full["feature"]}
    for level in pd.Series(key).dropna().unique():
        keep = key[key == level].index
        p = pairs[pairs["set_id"].isin(keep)]
        if p["set_id"].nunique() < min_sets:
            continue
        c = contrasts(df, p, list(full["feature"]), min_sets=min_sets)
        if c.empty:
            continue
        m = dict(zip(c["feature"], c["mean_diff"]))
        for f in sub_means:
            if f in m:
                sub_means[f].append(m[f])

    rows = []
    for _, r in full.iterrows():
        vals = np.array(sub_means[r["feature"]], dtype=float)
        if not len(vals):
            rows.append({"feature": r["feature"], f"{by}_sign_frac": np.nan,
                         f"{by}_cells": 0})
            continue
        rows.append({
            "feature": r["feature"],
            f"{by}_sign_frac": round(float((np.sign(vals)
                                            == np.sign(r["mean_diff"])).mean()), 3),
            f"{by}_worst": round(float(vals.min() if r["mean_diff"] > 0
                                       else vals.max()), 4),
            f"{by}_cells": int(len(vals)),
        })
    return pd.DataFrame(rows)


