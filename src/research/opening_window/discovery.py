"""Reverse discovery: start from the outcomes and work backwards to the setups.

WHAT CHANGES HERE, AND WHY
Every phase so far ran forwards: propose a rule, measure its forward return,
reject it. That has now rejected the 09:20 entry (H001), both stated filters
(H002), the tightening of either (H002), and the traded-payoff defence of all
three (H017). Running the same loop again with more indicators is the definition
of the thing that is not working.

So this phase inverts it. Take the *outcomes* as given, sort them into
path-aware kinds rather than winner/loser, and ask what the strong ones had in
common that superficially identical failures did not. The output is a shortlist
of candidate structures — "this type of breakout tends to work under these
conditions" — not a claim of alpha.

THE THREE THINGS THAT MAKE THIS HONEST RATHER THAN A FISHING TRIP

1. **Matched controls, not the pool average.** A winner is not compared against
   all 85,000 mornings. It is compared against a handful of mornings on the
   *same session*, in the same sector, at the same liquidity — and in the tight
   tier, with the same prior run-up, the same base tightness, the same gap and
   the same opening activity. Same-session matching is doing more work than any
   other choice in this module: it removes the market's return, the market's
   regime and the day's news exactly, without modelling any of them. The
   contrast is then "of two names that looked alike that morning, why did one
   run", which is the question actually asked.

2. **The null is the label shuffle inside the matched set.** A scan over ~60
   features produces a best feature whether or not anything is there. Permuting
   which member of each matched set is called the winner preserves every stratum
   — the date, the sector, the liquidity, the whole joint distribution — and
   destroys only the link between being the winner and the feature values. The
   maximum |t| over the whole scan under that null is the bar a finding has to
   clear, because a search reports a maximum.

3. **The fence.** `explore.fence()` raises on any row outside
   2023-08-21 .. 2026-08-18. The 2020-2023 backfill is the only genuinely
   unseen data this project has and this phase is explicitly permitted to
   overfit, so the fence is the only thing standing between "exploratory" and
   "worthless".

EVERY OUTPUT OF THIS MODULE IS EXPLORATORY / DATA-GENERATED
It is generated by the same data that would confirm it. `freeze()` writes the
survivors out in a form that can be replayed unchanged on the holdout, and
until that has happened nothing here is a result. This is stated in the module
that produces the numbers, not only in the write-up, because the write-up is
what gets skimmed.

WHY OUTCOME ARCHETYPES INSTEAD OF A RETURN
A fixed-horizon return scores the strategy's own payoff backwards (H017): a
setup that reaches +18% and gives it back looks identical to one that never
moved. The taxonomy here is path-aware — MFE, MAE, whether the stop was hit
before or after the favourable move, and how many sessions the move took — so
"it worked and I gave it back" and "it never worked" are different rows.
`monster`/`clean_winner` are the strong states; `failed_breakout` is the one
that matters most for the contrast, because a failed breakout is by
construction the superficially-identical failure the brief asks about.

THE BAR IS `max(k * R, floor)`, AND THE FLOOR IS NOT DECORATION
R is the distance from the entry to the stop, which on this pool has a median
around 2%. Defining a winner purely in R-multiples would let a morning with a
0.3% stop qualify as a 4R winner on a 1.2% move — the definition would then be
selecting tight stops, not winners. Every threshold is therefore the larger of
an R-multiple and an absolute percentage, and `sensitivity()` re-runs the whole
pipeline at nearby definitions so a finding that lives at one bar is visible.
"""
