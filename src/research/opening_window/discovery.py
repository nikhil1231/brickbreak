def report(t: int = 180, n_perm: int = 200, cluster_k: int = 4,
           verbose: bool = True) -> dict:
    """Run the reverse-discovery pipeline end to end and return the report.

    Order matters and is the argument of the phase: classify outcomes, validate
    the classification against the money, match, contrast, test the contrast
    against a permutation null and against nearby definitions, then ask whether
    any of it is large enough to act on. The last step is the one that is
    usually skipped, and on this data it is the one that changes the reading.
    """
    frame = load_frame(t, verbose=verbose)
    paths = build_outcomes(frame, verbose=verbose)
    paths = paths[paths["outcome"].notna()].reset_index(drop=True)
    w = paths["outcome"].isin(STRONG)
    c = paths["outcome"].isin(FAILURES)
    feats = all_features()

    out: dict = {"t_offset_s": t, "rows": int(len(paths)),
                 "symbols": int(paths["symbol"].nunique()),
                 "sessions": int(paths["date"].nunique()),
                 "window": [str(paths["date"].min().date()),
                            str(paths["date"].max().date())],
                 "base_win_rate_pct": round(float(w.mean() * 100), 2),
                 "EXPLORATORY": ("Every figure below is data-generated on the "
                                 "same window it was found in and confirms "
                                 "nothing. The 2020-2023 backfill is holdout.")}

    if verbose:
        print("\n== outcome archetypes ==")
    prof = outcome_profile(paths)
    out["outcome_profile"] = prof.to_dict("records")
    if verbose:
        print(prof.to_string(index=False))
        print("\n== the taxonomy, priced under the stated exit rule ==")
    out["payoff_validation"] = validate_against_payoff(
        paths, verbose=verbose).to_dict("records")

    out["tiers"] = {}
    for tier in ("core", "tight"):
        cfg = MatchConfig(tier=tier)
        if verbose:
            print(f"\n== matched contrasts: {tier} tier ==")
        pairs, st = match(paths, w, c, cfg, verbose=verbose)
        if pairs.empty:
            continue
        bal = balance(paths, pairs, list(cfg.covariates()) + ["size_tier_rank"])
        moff = market_offset(paths, pairs)
        con = contrasts(paths, pairs, feats)
        perm = permutation_null(paths, pairs, feats, n_perm=n_perm)
        stabs = [contrast_stability(paths, pairs, list(con["feature"].head(20)), by)
                 for by in ("period", "sector", "mkt_regime")]
        ranked = rank_contrasts(con, stabs, perm)
        out["tiers"][tier] = {
            "match": st, "balance": bal.to_dict("records"),
            "market_offset": moff,
            "permutation_null": perm,
            "contrasts": con.head(25).to_dict("records"),
            "ranked": ranked.to_dict("records"),
        }
        if verbose:
            cols = ["feature", "family", "n", "mean_diff", "std_diff", "t",
                    "pct_winner_higher"]
            print(con[cols].head(15).to_string(index=False))
            print(f"\n  permutation null over {perm['n_features']} features: "
                  f"max|t| p95 = {perm['perm_max_t_p95']}, "
                  f"max = {perm['perm_max_t_max']}")
            print(f"  worst covariate imbalance after matching (rank space): "
                  f"{bal['smd_after_rank'].abs().max():.3f}")
            if moff:
                print(f"  market-index offset, winner session vs controls': "
                      f"{moff['mean_pct']:+.4f}% "
                      f"({moff['pct_sets_winner_below']}% of sets below)")

    # The reader-facing form, and the one that decides whether any of this is
    # worth acting on.
    if verbose:
        print("\n== win rate by feature band (the same findings, in decision units) ==")
    top = [r["feature"] for r in out["tiers"]["core"]["contrasts"][:8]]
    profiles = []
    for f in top:
        pr = win_rate_profile(paths, w, f)
        if not pr.empty:
            profiles.append(pr)
            if verbose:
                print(pr.to_string(index=False))
    out["win_rate_profiles"] = (pd.concat(profiles).to_dict("records")
                                if profiles else [])

    if verbose:
        print("\n== does the effect survive holding extension fixed? ==")
    strat = stratified_win_rate(paths, w, "open_base_pos_20", "px_vs_ema_mid")
    out["stratified_open_base_pos_by_extension"] = (
        strat.to_dict() if not strat.empty else {})
    if verbose and not strat.empty:
        print(strat.to_string())

    if verbose:
        print("\n== winner clusters and their neighbourhoods ==")
    cprof, centres, cfeats = winner_clusters(paths, w, ClusterConfig(k=cluster_k),
                                             verbose=verbose)
    lifts = {}
    for r in (2.0, 5.0, 10.0):
        nl = neighbourhood_lift(paths, w, centres, cfeats, radius_pctile=r)
        lifts[str(r)] = nl.to_dict("records")
        if verbose:
            print(f"  radius {r}%: " + ", ".join(
                f"c{int(x['cluster'])} lift {x['lift']}" for _, x in nl.iterrows()))
    out["clusters"] = {"profile": cprof.round(3).to_dict("records"),
                       "features": cfeats,
                       "centroids": centres.round(4).tolist(),
                       "neighbourhood_lift": lifts}

    if verbose:
        print("\n== market regime ==")
    out["regime"] = {}
    for by in ("mkt_regime", "mkt_trend_eff", "mkt_ret_20d", "mkt_vol_20d",
               "mkt_breadth_pct"):
        rs = regime_split(paths, w, by)
        if not rs.empty:
            out["regime"][by] = rs.to_dict("records")
            if verbose:
                print(rs.to_string(index=False))
    inter = regime_interaction(paths, w, "open_base_pos_20", "mkt_regime")
    out["regime_interaction"] = inter.to_dict("records") if not inter.empty else []
    if verbose and not inter.empty:
        print("\n  open_base_pos_20 within regime:")
        print(inter.to_string(index=False))

    if verbose:
        print("\n== sensitivity to nearby definitions ==")
    sens = sensitivity(frame, top, verbose=verbose)
    out["sensitivity"] = (sens.reset_index().to_dict("records")
                          if not sens.empty else [])
    if verbose and not sens.empty:
        print(sens.to_string())

    return out
