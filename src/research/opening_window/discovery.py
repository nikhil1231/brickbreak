@dataclass(frozen=True)
class ClusterConfig:
    """k-means on the winners' own decision-time profile.

    Run on **within-date percentile ranks**, so a cluster cannot be "days when
    everything was heavy"; and on a deliberately small feature set, because
    k-means over sixty correlated columns finds the sixty-dimensional shape of
    the missing-data pattern rather than a trading setup.
    """
    k: int = 4
    seed: int = 0
    min_share: float = 0.05
    features: tuple[str, ...] = (
        "rs_20d_vs_mkt", "ret_20d", "px_vs_ema_mid", "dist_52w_high",
        "bb_width_pctile", "base_range_20_pct",
        "open_base_pos_20", "open_vs_high_20_pct", "days_since_high_20",
        "gap_pct", "entry_vs_open_pct", "time_above_open_frac",
        "vol_rel_daily_pct", "vol_hhi", "uptick_vol_share", "path_efficiency",
    )


def _kmeans(x: np.ndarray, k: int, seed: int, iters: int = 60
            ) -> tuple[np.ndarray, np.ndarray]:
    """Lloyd's algorithm with k-means++ seeding. No sklearn in this project."""
    rng = np.random.default_rng(seed)
    n = len(x)
    centres = [x[rng.integers(n)]]
    for _ in range(k - 1):
        d = np.min(((x[:, None, :] - np.array(centres)[None, :, :]) ** 2
                    ).sum(axis=2), axis=1)
        p = d / d.sum() if d.sum() > 0 else np.full(n, 1 / n)
        centres.append(x[rng.choice(n, p=p)])
    c = np.array(centres)
    lab = np.zeros(n, dtype=int)
    for _ in range(iters):
        d = ((x[:, None, :] - c[None, :, :]) ** 2).sum(axis=2)
        new = d.argmin(axis=1)
        if (new == lab).all():
            break
        lab = new
        for j in range(k):
            if (lab == j).any():
                c[j] = x[lab == j].mean(axis=0)
    return lab, c


def winner_clusters(df: pd.DataFrame, winner_mask: pd.Series,
                    cfg: ClusterConfig | None = None, verbose: bool = True
                    ) -> tuple[pd.DataFrame, np.ndarray, list[str]]:
    """Split the strong winners into several archetypes and describe each.

    The point of clustering here is the instruction not to force one global
    rule. If breakouts that work come in two or three recognisable kinds — a
    tight base breaking out through an old high on a small gap, and a
    high-relative-strength name gapping away from a shallow pullback, say —
    then a single averaged contrast will show the average of them, which may
    resemble neither.
    """
    cfg = cfg or ClusterConfig()
    feats = [f for f in cfg.features if f in df.columns]
    ranks = _rank_within_date(df, feats)
    # Median imputation *in rank space*, i.e. 0.5, which is "unremarkable for
    # that day". Imputing in raw units would invent a price.
    r = ranks.fillna(0.5)
    w = df.index[winner_mask & ranks.notna().mean(axis=1).ge(0.7)]
    x = r.loc[w].to_numpy(dtype=float)
    lab, centres = _kmeans(x, cfg.k, cfg.seed)

    prof = pd.DataFrame(centres, columns=feats)
    prof.insert(0, "n", [int((lab == j).sum()) for j in range(cfg.k)])
    prof.insert(0, "cluster", range(cfg.k))
    prof["share_pct"] = (prof["n"] / len(w) * 100).round(2)
    if verbose:
        print(f"  winner clusters: {len(w):,} strong winners into {cfg.k} groups "
              + ", ".join(f"c{j}={int(prof.loc[j, 'n']):,}" for j in range(cfg.k)))
    return prof, centres, feats


def neighbourhood_lift(df: pd.DataFrame, winner_mask: pd.Series,
                       centres: np.ndarray, feats: list[str],
                       radius_pctile: float = 5.0) -> pd.DataFrame:
    """The number that matters: how often does a *lookalike* morning win?

    Every morning in the pool — winners and failures alike — is assigned to its
    nearest winner centroid in rank space, and kept only if it falls inside the
    tightest `radius_pctile` percent of all distances. The win rate inside that
    neighbourhood against the pool's base rate is the candidate structure, and
    it is the honest form of the claim: not "winners had a high X" (which is
    survivorship read backwards) but "mornings that looked like this won more
    often".

    Clustered by session, and reported with the base rate beside it so a lift
    of 1.3x on a 4% base rate cannot be mistaken for a 30% edge.
    """
    ranks = _rank_within_date(df, feats).fillna(0.5)
    x = ranks.to_numpy(dtype=float)
    d = ((x[:, None, :] - centres[None, :, :]) ** 2).sum(axis=2)
    nearest, dist = d.argmin(axis=1), np.sqrt(d.min(axis=1))
    base = float(winner_mask.mean() * 100)

    rows = []
    for j in range(len(centres)):
        m = nearest == j
        if not m.any():
            continue
        cut = np.percentile(dist[m], radius_pctile)
        inside = m & (dist <= cut)
        y = winner_mask[inside].astype(float) * 100
        s = explore.cluster_stats(y, df.loc[inside, "date"])
        rows.append({
            "cluster": j, "n_inside": int(inside.sum()),
            "win_pct": round(float(y.mean()), 2),
            "base_pct": round(base, 2),
            "lift": round(float(y.mean()) / base, 2) if base > 0 else np.nan,
            "t": s["t"], "naive_t": s["naive_t"], "n_dates": s["n_dates"],
            "radius": round(float(cut), 4),
        })
    return pd.DataFrame(rows)


