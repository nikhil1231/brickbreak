def quantile_profile(df: pd.DataFrame, col: str, y: str, q: int = 5,
                     within_date: bool = False) -> pd.DataFrame:
    """Outcome by quantile of one feature. The blunt instrument, used first.

    `within_date` ranks inside each session before cutting, which removes the
    market-wide component of the feature. For `_xr` columns the ranking has
    already happened and this should stay False.
    """
    d = df[[col, y, "date"]].dropna(subset=[col])
    if d.empty:
        return pd.DataFrame()
    v = d.groupby("date")[col].rank(pct=True) if within_date else d[col]
    try:
        b = pd.qcut(v, q, labels=False, duplicates="drop")
    except ValueError:
        return pd.DataFrame()
    rows = []
    for k, sub in d.groupby(b, observed=True):
        s = cluster_stats(sub[y], sub["date"])
        s |= {"feature": col, "q": int(k) + 1,
              "lo": round(float(sub[col].min()), 4),
              "hi": round(float(sub[col].max()), 4)}
        rows.append(s)
    out = pd.DataFrame(rows)
    if out.empty:
        return out
    # Monotonicity across quantiles: a feature whose effect climbs steadily is a
    # much better candidate than one whose middle bucket happens to be best.
    mm = out["mean"].to_numpy()
    out["spread"] = round(float(mm[-1] - mm[0]), 4)
    out["monotone"] = float(np.mean(np.sign(np.diff(mm)) == np.sign(mm[-1] - mm[0])))
    return out


@dataclass(frozen=True)
class ScanConfig:
    """Search shape. `q=3` is a choice about honesty, not about resolution.

    Terciles of a cross-sectional rank give broad regions with no free decimal
    to tune. Quintiles are available for the univariate pass, where the
    multiple-comparison cost is small; interactions stay at terciles because a
    5x5 grid over 30 features is 15,000 cells and would find something
    beautiful in pure noise.
    """
    q: int = 3
    min_n: int = 400
    y: str = "excess_ret_5d_pct"
    t_offsets: tuple[int, ...] = (60, 120, 180, 300)


def _tercile(s: pd.Series, q: int) -> pd.Series:
    try:
        return pd.qcut(s, q, labels=False, duplicates="drop")
    except ValueError:
        return pd.Series(np.nan, index=s.index)


def interaction_grid(df: pd.DataFrame, a: str, b: str, cfg: ScanConfig
                     ) -> list[dict]:
    """Every cell of a coarse two-feature grid, with a robustness-to-nudge check.

    `nudge_min` is the point of this function. For each cell it re-evaluates the
    effect on the neighbouring cells along both axes and reports the worst of
    them. A genuine broad region has neighbours that look similar; a fitted
    crevice is surrounded by cells that look nothing like it, and the ranking
    later punishes exactly that.
    """
    d = df[[a, b, cfg.y, "date"]].dropna(subset=[a, b])
    if len(d) < cfg.min_n:
        return []
    ka, kb = _tercile(d[a], cfg.q), _tercile(d[b], cfg.q)
    if ka.isna().all() or kb.isna().all():
        return []

    cells: dict[tuple[int, int], dict] = {}
    for (i, j), sub in d.groupby([ka, kb], observed=True):
        if len(sub) < cfg.min_n:
            continue
        cells[(int(i), int(j))] = cluster_stats(sub[cfg.y], sub["date"]) | {
            "feature_a": a, "feature_b": b, "ia": int(i), "ib": int(j)}

    out = []
    for (i, j), rec in cells.items():
        neigh = [cells[(i + di, j + dj)]["mean"]
                 for di, dj in ((-1, 0), (1, 0), (0, -1), (0, 1))
                 if (i + di, j + dj) in cells]
        if rec["mean"] > 0:
            rec["nudge_min"] = round(min([rec["mean"]] + neigh), 4)
        else:
            rec["nudge_min"] = round(max([rec["mean"]] + neigh), 4)
        rec["n_neighbours"] = len(neigh)
        out.append(rec)
    return out


def scan_univariate(df: pd.DataFrame, features: list[str], cfg: ScanConfig,
                    q: int = 5) -> pd.DataFrame:
    """Every feature against the outcome, one at a time, per entry time."""
    fence(df, "scan frame")
    rows = []
    for t in cfg.t_offsets:
        sub = df[df["t_offset_s"] == t]
        if sub.empty:
            continue
        for f in features:
            if f not in sub.columns:
                continue
            prof = quantile_profile(sub, f, cfg.y, q=q)
            if prof.empty:
                continue
            prof["t_offset_s"] = t
            rows.append(prof)
    return pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()


def scan_interactions(df: pd.DataFrame, features: list[str], cfg: ScanConfig
                      ) -> pd.DataFrame:
    """All feature pairs, coarse grid, per entry time. Reports cells, not winners."""
    fence(df, "scan frame")
    rows = []
    for t in cfg.t_offsets:
        sub = df[df["t_offset_s"] == t]
        if sub.empty:
            continue
        have = [f for f in features if f in sub.columns]
        for a, b in itertools.combinations(have, 2):
            for rec in interaction_grid(sub, a, b, cfg):
                rec["t_offset_s"] = t
                rows.append(rec)
    return pd.DataFrame(rows)


def rank_findings(cells: pd.DataFrame, df: pd.DataFrame, cfg: ScanConfig,
                  top: int = 25) -> pd.DataFrame:
    """Triage order over candidate cells. Not a score, not a probability.

    Deliberately blunt and deliberately conservative: a cell is only interesting
    if it is large, survives clustering, has enough rows to be measured, keeps
    its sign when the sample is cut by period and sector, and does not
    evaporate when its boundaries move one step. Any of those failing drags the
    cell down; none of them passing makes it true.
    """
    if cells.empty:
        return cells
    c = cells[(cells["n"] >= cfg.min_n) & cells["t"].notna()].copy()
    if c.empty:
        return c
    c["abs_t"] = c["t"].abs()
    # Shrink toward zero by sample size: the same effect on 400 rows and on
    # 12,000 rows is not the same evidence.
    c["effect"] = c["mean"].abs()
    c["nudge_keep"] = (c["nudge_min"].abs() / c["effect"].replace(0, np.nan)
                       ).clip(0, 1) if "nudge_min" in c else 1.0
    c["nudge_keep"] = c["nudge_keep"].fillna(0.0)
    # Same sign as the cell, or the neighbourhood contradicts it outright.
    if "nudge_min" in c:
        c.loc[np.sign(c["nudge_min"]) != np.sign(c["mean"]), "nudge_keep"] = 0.0

    stab = []
    for _, r in c.iterrows():
        sub = df[df["t_offset_s"] == r["t_offset_s"]]
        m = pd.Series(True, index=sub.index)
        for fcol, icol in (("feature_a", "ia"), ("feature_b", "ib")):
            if fcol in r and pd.notna(r.get(fcol)):
                k = _tercile(sub[r[fcol]], cfg.q)
                m &= (k == r[icol])
        st = stability(sub, m, cfg.y)
        stab.append(st)
    st = pd.DataFrame(stab, index=c.index)
    c = pd.concat([c, st], axis=1)

    per = c.get("period_sign_frac", pd.Series(0.0, index=c.index)).fillna(0.0)
    sec = c.get("sector_sign_frac", pd.Series(0.0, index=c.index)).fillna(0.0)
    c["triage"] = (
        c["effect"].clip(0, 3) / 3.0 * 0.30
        + (c["abs_t"] / 4.0).clip(0, 1) * 0.25
        + (np.log10(c["n"]) / 4.5).clip(0, 1) * 0.10
        + per * 0.15 + sec * 0.10 + c["nudge_keep"] * 0.10
    ).round(4)
    return c.sort_values("triage", ascending=False).head(top).reset_index(drop=True)


def load_explore_frame(verbose: bool = True) -> pd.DataFrame:
    """The single frame everything in this module runs on."""
    from . import behaviour
    panel = behaviour.load()
    fence(panel, "behaviour panel")
    d = attach_context(panel)
    d = attach_outcomes(d, verbose=verbose)
    if verbose:
        print(f"  explore frame: {len(d):,} rows, "
              f"{d['symbol'].nunique():,} symbols, {d['date'].nunique():,} sessions, "
              f"{d['date'].min().date()} .. {d['date'].max().date()}")
    return d
