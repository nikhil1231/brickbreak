"""Exploratory search over the opening-behaviour family. Nothing here is a result.

WHAT THIS IS FOR
H001 and H002 rejected the 09:20 entry and the two stated filters. H008 reframes
the question: the strategy is plausibly recognising a *developing behaviour*, not
evaluating thresholds at a fixed second. This module searches that bounded family
— daily context, sector/trend context, and the evolving opening — for
relationships worth freezing and testing later on data that has not been looked
at.

THE BRIGHT LINE, ENFORCED IN CODE RATHER THAN IN A COMMENT
Every finding this module produces is **EXPLORATORY / DATA-GENERATED**. It is
generated by the same data that would "confirm" it, so it confirms nothing. The
2020-04 → 2023-08 backfill is holdout: `fence()` raises on any row outside
2023-08-21 → 2026-08-18, and it is called at the top of every entry point here.
The fence exists because the discipline is worthless if a stray `date_min` can
quietly breach it.

FOUR WAYS THIS SEARCH COULD LIE, AND WHAT IS DONE ABOUT EACH

1. **Cross-sectional correlation.** 64,000 mornings are not 64,000 independent
   observations; they are ~650 sessions, and on any given session everything
   moves together. A naive t-stat over the rows is inflated by roughly the
   square root of the average cluster size. Every t-stat here is **clustered by
   date**, and `naive_t` is reported alongside so the size of the lie is
   visible rather than assumed away.

2. **Multiple comparisons.** A scan over hundreds of cells will produce a best
   cell whether or not anything is there. `permutation_max` reports how many
   cells were tested and a **within-date permutation null** for the *maximum*
   |t| over the whole family — the honest comparison for a search, since a
   search reports a maximum. A cell that clears its own t-threshold but not the
   permuted maximum is noise with a good haircut.

3. **Optimising into a crevice.** The failure mode the user named explicitly:
   `EMA = 17.3, gap 0.63-0.91%, volume 8.7-11.2%, entry at 94 seconds`. Defended
   structurally, not by taste. Features are cut at **terciles and quintiles of
   their own cross-sectional rank**, so there are no free decimal thresholds to
   tune; and every cell reports `nudge_min`, the worst effect obtained when each
   boundary is moved one grid step in either direction. A cell whose effect
   survives only at its exact boundaries is reported as unstable, and ranking
   punishes it.

4. **Regime.** 2023-2026 is one rising market. Every finding carries a
   subperiod split (thirds of the sample), a sector split and a size split, and
   `stability` counts how many of those subsets keep the sign. An effect that
   lives in one year or one sector is reported as such.

WHAT RANKING MEANS HERE
`rank_findings` orders by a deliberately blunt composite of effect size,
clustered t, sample size, sign-stability across subperiods and sectors, and
nudge robustness. It is a triage order for what to freeze and test out of
sample. It is **not** a score, not a probability, and not an argument that the
top row is real.
"""
from __future__ import annotations

import itertools
from dataclasses import dataclass

import numpy as np
import pandas as pd

from ....core import config
from ....research_data import repository
from . import labelling

# The fence. 2023-08-21 is the first session of the original pull; everything
# before it belongs to the backfill and is holdout.
EXPLORE_START = pd.Timestamp("2023-08-21")
EXPLORE_END = pd.Timestamp("2026-08-18")

HORIZONS = (1, 3, 5, 10)


class HoldoutBreach(RuntimeError):
    """Raised when exploration code is handed data it is not allowed to see."""


def fence(df: pd.DataFrame, what: str = "frame") -> pd.DataFrame:
    """Refuse to proceed on any row outside the exploration window.

    Deliberately raises rather than filtering. Silently dropping holdout rows
    would make a breach invisible, and the whole point of the split is that a
    breach must be loud.
    """
    if "date" not in df.columns:
        raise HoldoutBreach(f"{what} has no date column; cannot verify the split")
    lo, hi = df["date"].min(), df["date"].max()
    if pd.isna(lo):
        return df
    if lo < EXPLORE_START or hi > EXPLORE_END:
        raise HoldoutBreach(
            f"{what} spans {lo.date()} .. {hi.date()}, outside the exploration "
            f"window {EXPLORE_START.date()} .. {EXPLORE_END.date()}. The "
            f"2020-2023 backfill is holdout: exploring on it destroys the only "
            f"out-of-sample test this project has."
        )
    return df


