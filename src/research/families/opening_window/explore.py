def cluster_stats(y: pd.Series, dates: pd.Series) -> dict:
    """Mean and t-statistic with standard errors clustered by session.

    Mornings on the same date share a market. Treating them as independent
    inflates every t-statistic by roughly sqrt(average cluster size), which here
    is about 10x — enough to turn noise into a publishable-looking result. The
    clustered estimator is the one-way CR0 form: sum the within-date residual
    totals, not the individual residuals.
    """
    m = y.notna()
    y, dates = y[m], dates[m]
    n = len(y)
    if n < 2:
        return {"n": int(n), "mean": np.nan, "t": np.nan, "naive_t": np.nan,
                "n_dates": 0}
    mean = float(y.mean())
    resid = y - mean
    by_date = resid.groupby(dates).sum()
    g = len(by_date)
    # Var(mean) = sum_g (sum_i e_ig)^2 / n^2, with the usual small-G correction.
    var = float((by_date ** 2).sum()) / (n ** 2)
    if g > 1:
        var *= g / (g - 1)
    se = float(np.sqrt(var)) if var > 0 else np.nan
    naive_se = float(y.std() / np.sqrt(n)) if n > 1 else np.nan
    return {
        "n": int(n),
        "n_dates": int(g),
        "mean": round(mean, 4),
        "median": round(float(y.median()), 4),
        "hit_pct": round(float((y > 0).mean() * 100), 2),
        "t": round(mean / se, 2) if se and se > 0 else np.nan,
        "naive_t": round(mean / naive_se, 2) if naive_se and naive_se > 0 else np.nan,
    }


def _splits(df: pd.DataFrame) -> dict[str, pd.Series]:
    """The subsets every finding must survive to be called stable.

    Thirds of the calendar (regime), sector, and size tier. Sector and size are
    included because a "behavioural" effect that turns out to be one sector's
    beta or one liquidity tier's microstructure is not the behaviour it claims
    to be.
    """
    out = {}
    dates = df["date"]
    q = dates.rank(pct=True)
    out["period"] = pd.cut(q, [0, 1 / 3, 2 / 3, 1.0],
                           labels=["p1", "p2", "p3"], include_lowest=True)
    if "sector" in df.columns:
        out["sector"] = df["sector"]
    if "size_tier" in df.columns:
        out["size_tier"] = df["size_tier"]
    return out


def stability(df: pd.DataFrame, mask: pd.Series, y: str,
              min_n: int = 150) -> dict:
    """How much of the effect's sign survives cutting the sample up.

    Reports the fraction of subsets keeping the full-sample sign, and the worst
    subset effect. Subsets below `min_n` are excluded rather than counted, since
    a 40-row sector cell voting on stability is noise voting on noise.
    """
    sub = df[mask]
    if sub.empty:
        return {}
    full = sub[y].mean()
    if not np.isfinite(full):
        return {}
    out = {}
    for name, key in _splits(df).items():
        k = key[mask]
        grp = sub.groupby(k, observed=True)[y].agg(["mean", "count"])
        grp = grp[grp["count"] >= min_n]
        if grp.empty:
            continue
        same = float((np.sign(grp["mean"]) == np.sign(full)).mean())
        out[f"{name}_sign_frac"] = round(same, 3)
        out[f"{name}_worst"] = round(float(grp["mean"].min() if full > 0
                                           else grp["mean"].max()), 4)
        out[f"{name}_n_cells"] = int(len(grp))
    return out


def permutation_max(df: pd.DataFrame, masks: list[pd.Series], y: str,
                    n_perm: int = 200, seed: int = 0) -> dict:
    """What the best cell in this scan would look like if nothing were there.

    Shuffles the outcome **within each session**. That is the null the search
    actually needs: it keeps every session's own mean and dispersion — so the
    market's common movement and the fat days are all still there — and destroys
    only the link between a morning's features and its own future, which is the
    thing being claimed.

    An earlier version of this function shuffled *date-level means* between
    dates and left each row's within-date deviation attached to it. That null
    preserves the entire cross-sectional relationship being tested, so a real
    cross-sectional effect survives into the "null" unchanged and the test is
    vacuous — it cannot reject anything. Any figure produced that way is
    meaningless and must not be quoted.

    Reports the distribution of the maximum |t| over the whole family of cells,
    because a search reports a maximum and a maximum is what has to be beaten.
    """
    rng = np.random.default_rng(seed)
    dates = df["date"]
    vals = df[y].to_numpy(dtype=float)
    # Row positions grouped by date, so each permutation is a within-date shuffle.
    order = np.argsort(dates.to_numpy(), kind="stable")
    grouped = np.split(order, np.unique(dates.to_numpy()[order],
                                        return_index=True)[1][1:])
    mask_arrays = [m.to_numpy() for m in masks]

    maxes = []
    for _ in range(n_perm):
        yy = vals.copy()
        for idx in grouped:
            if len(idx) > 1:
                yy[idx] = vals[rng.permutation(idx)]
        ys = pd.Series(yy, index=df.index)
        best = 0.0
        for m in mask_arrays:
            s = cluster_stats(ys[m], dates[m])
            tv = s.get("t")
            if tv is not None and np.isfinite(tv):
                best = max(best, abs(tv))
        maxes.append(best)
    maxes = np.array(maxes)
    return {
        "n_perm": int(n_perm),
        "n_cells": int(len(masks)),
        "perm_max_t_p50": round(float(np.percentile(maxes, 50)), 2),
        "perm_max_t_p90": round(float(np.percentile(maxes, 90)), 2),
        "perm_max_t_p95": round(float(np.percentile(maxes, 95)), 2),
        "perm_max_t_max": round(float(maxes.max()), 2),
    }


