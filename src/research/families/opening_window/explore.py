def attach_outcomes(panel: pd.DataFrame, horizons: tuple[int, ...] = HORIZONS,
                    verbose: bool = True) -> pd.DataFrame:
    """Forward and excess returns measured from `price_t`, not from `close_5m`.

    The existing labels enter at 09:20 (H001). Re-using them here would answer
    the wrong question: the whole point of the behavioural panel is that the
    entry happens *inside* the window, and H003 showed the window itself moves
    against these mornings by 0.3-0.7%. The entry price must therefore be the
    price at `t`.

    The three corrections from `labelling.py` still apply and are applied here:
    the raw tick entry is lifted onto the adjusted basis before any division,
    forward sessions come off the full daily panel rather than the candidate
    panel, and truncated horizons are NaN rather than a short-window number.
    """
    fence(panel, "behaviour panel")
    bars = repository.daily_bars(
        columns=["symbol", "date", "series", "open", "high", "low", "close"])
    fwd = labelling._forward_arrays(bars, horizons)
    cfg = labelling.LabelConfig(horizons=horizons)
    bench = labelling._benchmark(bars, fwd, cfg)

    d = panel.merge(fwd, on=["symbol", "date"], how="left")
    entry = (d["price_t"] * d["adj_factor"]).where(d["price_t"] > 0)
    d["entry_px_adj"] = entry

    for h in horizons:
        complete = d["n_fwd_sessions"] >= h
        d[f"fwd_ret_{h}d_pct"] = ((d[f"fwd_close_{h}"] / entry - 1) * 100).where(complete)
        d[f"mfe_{h}d_pct"] = ((d[f"fwd_high_{h}"] / entry - 1) * 100).where(complete)
        d[f"mae_{h}d_pct"] = ((d[f"fwd_low_{h}"] / entry - 1) * 100).where(complete)
    d = d.merge(bench, on="date", how="left")
    for h in horizons:
        d[f"excess_ret_{h}d_pct"] = (d[f"fwd_ret_{h}d_pct"]
                                     - d[f"bench_fwd_ret_{h}d_pct"])

    drop = [c for c in d.columns
            if c.startswith(("fwd_close_", "fwd_high_", "fwd_low_", "fwd_date_"))
            or c in ("d0_high", "d0_low")]
    d = d.drop(columns=drop)
    if verbose:
        n = d[f"excess_ret_5d_pct"].notna().sum()
        print(f"  outcomes attached to {len(d):,} rows ({n:,} with a complete +5d)")
    return d


def attach_context(panel: pd.DataFrame, cols: tuple[str, ...] | None = None
                   ) -> pd.DataFrame:
    """Join the daily setup context — trend, contraction, sector, gap, liquidity.

    The behavioural panel describes the opening. The strategy family also spans
    what the stock looked like *before* it opened, and the interactions the user
    asked about ("tight contraction + sector trend + modest gap + volume
    acceleration") live across that boundary, so both halves have to be on one
    row.
    """
    default = (
        "sector", "size_tier", "size_tier_rank", "gap_pct", "deliv_pct",
        "ema_stack_up", "above_ema_mid", "px_vs_ema_mid", "ema_mid_slope",
        "ret_20d", "ret_60d", "dist_52w_high",
        "bb_width_pctile", "atr_ratio_pctile", "base_depth_pctile",
        "contraction_steps", "nr_k", "vol_squeeze", "inside_day", "body_ratio",
        "sec_slope", "sector_uptrend_index", "sector_breadth",
    )
    cols = cols or default
    cand = repository.candidate_labels()
    keep = ["symbol", "date"] + [c for c in cols if c in cand.columns]
    return panel.merge(cand[keep], on=["symbol", "date"], how="inner")


